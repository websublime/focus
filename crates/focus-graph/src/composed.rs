//! Composed scopes: plans a person approved and saved as a scope of their own.
//!
//! A stock scope's grid column comes from stage frontmatter (`scopes:`), so a
//! recompile always regenerates it. A composed scope has no such producer: its
//! column exists only because a `compose` run wrote it. A recompile that
//! transposed the stages and nothing else would drop it, and with the scope's
//! identity file still present the name would stay valid and resolve to a plan
//! with every stage skipped.
//!
//! So a composed scope is kept in two places and the compile reconciles them:
//!
//! - the **record**, `focus/scopes/<name>.md`: the team-owned, harness-neutral
//!   source. It is the scope's identity file followed by a generated region
//!   holding the grid column.
//! - the **projection** into each harness tree: the identity file under
//!   `<harness>/scopes/` and the column in `scope-grid.json`.
//!
//! Mirrors `aidlc-graph.ts` L490–857 and L2183–2311.

use std::path::{Path, PathBuf};

use focus_frontmatter as fm;
use focus_js::order::{cmp_utf16, js_key_order};
use focus_js::{EngineError, Result, bail, json, re};
use focus_workspace::atomic::write_atomic;
use focus_workspace::links::refuse_link_on_the_way;
use focus_workspace::observer;
use serde_json::{Map, Value};

use crate::fsx::{read_dir_sorted, read_text};
use crate::scopes::{SCOPE_NAME_RULE, is_scope_name};

/// Opens the generated region of a record. A record parses only when this
/// line is present byte for byte, so the text is part of the on-disk format
/// and stays upstream's, including the command it names.
pub const GRID_BEGIN: &str = "<!-- BEGIN focus composed-scope-grid: generated by `focus engine graph compile` — reshape the plan through /focus compose, not by editing here -->";
/// Closes the generated region of a record.
pub const GRID_END: &str = "<!-- END focus composed-scope-grid -->";

/// A composed scope's durable record.
#[derive(Debug, Clone, PartialEq)]
pub struct Record {
    /// The scope name from frontmatter: the grid key and the `--scope` value.
    pub name: String,
    /// The harness-tree projection: everything above the generated region.
    pub identity: String,
    /// Stage slug to `EXECUTE` or `SKIP`, in the record's own order.
    pub stages: Map<String, Value>,
}

/// Split a record into its identity and its grid.
///
/// # Errors
///
/// Any malformed input, with the file named. A record is user data whose whole
/// purpose is to survive a recompile, so nothing is skipped silently.
pub fn parse_record(body: &str, shown: &str) -> Result<Record> {
    let Some(block) = fm::frontmatter_block(body) else {
        bail!("Composed scope record missing frontmatter: {shown}");
    };
    let name = fm::scalar_field(block, "name");
    if name.is_empty() {
        bail!("Composed scope record {shown} missing required frontmatter: name");
    }
    if !is_scope_name(&name) {
        bail!(
            "Composed scope record {shown} has a name a scope cannot have. Rename the scope to {SCOPE_NAME_RULE}."
        );
    }

    // Exactly one pair of sentinels. Counted, not searched from one end, so a
    // hand-edited record never resolves to whichever end was looked at first.
    let begins = body.matches(GRID_BEGIN).count();
    let ends = body.matches(GRID_END).count();
    if begins == 0 || ends == 0 {
        bail!(
            "Composed scope record {shown} has no generated grid region. It must end with the `{GRID_BEGIN}` / `{GRID_END}` sentinel pair wrapping a ```json fence with {{\"stages\": {{...}}}}. Recover by deleting this record and re-running compile (the harness pair is back-filled), or by restoring the region by hand."
        );
    }
    if begins > 1 || ends > 1 {
        bail!(
            "Composed scope record {shown} has {begins} BEGIN and {ends} END grid sentinels; exactly one of each is required. Remove the duplicates so the generated region is unambiguous."
        );
    }
    let begin_at = body.find(GRID_BEGIN).unwrap_or(0);
    let end_at = body.find(GRID_END).unwrap_or(0);
    if end_at < begin_at {
        bail!("Composed scope record {shown} has its END grid sentinel before its BEGIN sentinel.");
    }

    // The fence is looked for only inside the region, so a ```json fence in
    // the authored prose above it is never taken for the grid.
    let region = &body[begin_at + GRID_BEGIN.len()..end_at];
    let Some(fence) = re::find(r"```json\s*\n([\s\S]*?)```", "", region) else {
        bail!(
            "Composed scope record {shown} has a generated grid region with no ```json fence inside it."
        );
    };
    let fenced = re::group(region, &fence, 1).unwrap_or("");
    let parsed = json::parse(fenced).map_err(|err| {
        EngineError::new(format!(
            "Composed scope record {shown} has an unparseable grid fence: {err}"
        ))
    })?;
    let Some(Value::Object(raw)) = parsed.get("stages") else {
        bail!(
            "Composed scope record {shown}: the grid fence must be an object with a \"stages\" member mapping stage slugs to EXECUTE or SKIP."
        );
    };
    for (slug, action) in raw {
        if !matches!(action.as_str(), Some("EXECUTE" | "SKIP")) {
            bail!(
                "Composed scope record {shown}: stage \"{slug}\" has invalid action {} (expected EXECUTE or SKIP).",
                json::stringify(action)
            );
        }
    }
    Ok(Record {
        name,
        identity: collapse_trailing_newlines(&body[..begin_at]),
        stages: raw.clone(),
    })
}

/// `s.replace(/\n+$/, "\n")`: a run of trailing newlines collapses to one; a
/// string that does not end in a newline is left as it is.
fn collapse_trailing_newlines(s: &str) -> String {
    let trimmed = s.trim_end_matches('\n');
    if trimmed.len() == s.len() {
        s.to_owned()
    } else {
        format!("{trimmed}\n")
    }
}

/// Render a record from an identity file and a grid column: the identity,
/// then the generated region. Parsing the result gives the same two back.
///
/// # Errors
///
/// The identity already contains a sentinel. Rendering it would produce a
/// record with two regions, which then fails to parse on every later compile;
/// refusing here names the cause where the bad input arrives.
pub fn render_record(
    identity: &str,
    stages: &Map<String, Value>,
    identity_path: Option<&str>,
) -> Result<String> {
    if identity.contains(GRID_BEGIN) || identity.contains(GRID_END) {
        bail!(
            "Composed scope identity{} already contains an focus composed-scope-grid sentinel; it must hold only the authored scope file, not a generated grid region.",
            identity_path.map(|p| format!(" {p}")).unwrap_or_default()
        );
    }
    let mut wrapper = Map::new();
    wrapper.insert("stages".to_owned(), Value::Object(stages.clone()));
    Ok(format!(
        "{}\n\n{GRID_BEGIN}\n\n```json\n{}\n```\n\n{GRID_END}\n",
        identity.trim_end_matches('\n'),
        json::stringify_pretty(&Value::Object(wrapper))
    ))
}

/// Load every record in `dir`, in file-name order. A missing directory is the
/// common case (nothing composed yet) and reads as no records.
///
/// # Errors
///
/// A record that does not parse, or two records declaring one name.
pub fn load_records(dir: &Path) -> Result<Vec<Record>> {
    let Ok(files) = read_dir_sorted(dir) else {
        return Ok(Vec::new());
    };
    let mut out: Vec<Record> = Vec::new();
    for file in files.into_iter().filter(|f| f.ends_with(".md")) {
        let path = dir.join(&file);
        let shown = path.display().to_string();
        let record = parse_record(&read_text(&path)?, &shown)?;
        if out.iter().any(|seen| seen.name == record.name) {
            bail!(
                "Duplicate composed scope name \"{}\" in {shown}. Rename one of them.",
                record.name
            );
        }
        out.push(record);
    }
    Ok(out)
}

/// Which composed scopes a compile carries forward, and their columns.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct FoldBack {
    /// The composed columns, keyed by scope name, sorted.
    pub grid: Map<String, Value>,
    /// Every composed scope carried forward, sorted.
    pub names: Vec<String>,
    /// Those that came from a record.
    pub record_names: Vec<String>,
    /// Those that exist only as a column in the installed grid: an install
    /// composed before records existed. The write side gives each a record.
    pub grid_only_names: Vec<String>,
}

/// Decide what a compile folds back into the freshly transposed grid.
///
/// Records win, because the harness grid is a projection of them. A column in
/// the installed grid that no stage declares and no record covers is carried
/// too, as a migration path. Either way the scope's identity file must be
/// installed: a column without one is an orphan, not a composed scope, and is
/// left to be dropped.
#[must_use]
pub fn fold_back(
    records: &[Record],
    on_disk_grid: Option<&str>,
    stock: &[&str],
    installed: &[&str],
) -> FoldBack {
    let mut record_names: Vec<String> = records
        .iter()
        .map(|r| r.name.as_str())
        .filter(|name| !stock.contains(name) && installed.contains(name))
        .map(str::to_owned)
        .collect();
    record_names.sort_by(|a, b| cmp_utf16(a, b));

    // An unparseable installed grid contributes nothing; records still fold.
    let on_disk = match on_disk_grid.map(json::parse) {
        Some(Ok(Value::Object(map))) => map,
        _ => Map::new(),
    };
    let mut grid_only_names: Vec<String> = on_disk
        .keys()
        .filter(|name| {
            !stock.contains(&name.as_str())
                && is_scope_name(name)
                && installed.contains(&name.as_str())
                && !record_names.contains(name)
        })
        .cloned()
        .collect();
    grid_only_names.sort_by(|a, b| cmp_utf16(a, b));

    let mut merged: Vec<(String, Value)> = Vec::new();
    for name in &grid_only_names {
        if let Some(entry) = on_disk.get(name).filter(|entry| is_grid_entry(entry)) {
            merged.push((name.clone(), entry.clone()));
        }
    }
    for name in &record_names {
        if let Some(record) = records.iter().find(|r| r.name == *name) {
            let mut entry = Map::new();
            entry.insert("stages".to_owned(), Value::Object(record.stages.clone()));
            merged.push((name.clone(), Value::Object(entry)));
        }
    }
    merged.sort_by(|(a, _), (b, _)| cmp_utf16(a, b));

    let mut names: Vec<String> = record_names
        .iter()
        .chain(&grid_only_names)
        .cloned()
        .collect();
    names.sort_by(|a, b| cmp_utf16(a, b));
    FoldBack {
        grid: js_key_order(merged.into_iter().collect()),
        names,
        record_names,
        grid_only_names,
    }
}

/// What upstream accepts as a grid column: an object whose `stages` member is
/// an object in the JS sense (`typeof x === "object"`, which includes arrays
/// and `null`).
fn is_grid_entry(entry: &Value) -> bool {
    entry.as_object().is_some_and(|object| {
        matches!(
            object.get("stages"),
            Some(Value::Object(_) | Value::Array(_) | Value::Null)
        )
    })
}

/// Add the composed columns to a freshly transposed grid. A name the
/// transpose already produced keeps the transposed column; the result is
/// sorted by scope name.
#[must_use]
pub fn merge(fresh: Map<String, Value>, composed: &FoldBack) -> Map<String, Value> {
    let mut merged: Vec<(String, Value)> = fresh.into_iter().collect();
    for (name, entry) in &composed.grid {
        let known = merged.iter().any(|(seen, _)| seen == name);
        if !known && composed.names.contains(name) && is_grid_entry(entry) {
            merged.push((name.clone(), entry.clone()));
        }
    }
    merged.sort_by(|(a, _), (b, _)| cmp_utf16(a, b));
    js_key_order(merged.into_iter().collect())
}

/// The installed scope identity file that declares `name`. Matched on
/// frontmatter, not on the file name, so a scope whose file was renamed still
/// round-trips.
#[must_use]
pub fn identity_file_for(scopes_dir: &Path, name: &str) -> Option<PathBuf> {
    read_dir_sorted(scopes_dir)
        .ok()?
        .into_iter()
        .filter(|f| f.ends_with(".md"))
        .map(|f| scopes_dir.join(f))
        .find(|path| {
            read_text(path).ok().is_some_and(|body| {
                fm::frontmatter_block(&body)
                    .is_some_and(|block| fm::scalar_field(block, "name") == name)
            })
        })
}

/// `file` inside `dir`, refused when the joined path would land anywhere else.
/// The directory a file is about to be written into, made when missing: the
/// write itself creates none.
fn make_dir(dir: &Path) -> Result<()> {
    std::fs::create_dir_all(dir)
        .map_err(|err| EngineError::new(format!("{}: {err}", dir.display())))
}

fn file_inside(dir: &Path, file: &str) -> Result<PathBuf> {
    let path = dir.join(file);
    let single = Path::new(file).components().count() == 1
        && !file.contains(['/', '\\'])
        && file != ".."
        && file != ".";
    if !single {
        bail!(
            "Refusing to write {}: it is not inside {}.",
            path.display(),
            dir.display()
        );
    }
    Ok(path)
}

/// Project records into a harness tree: write `scopes/focus-<name>.md` for
/// each record whose identity file is absent. This is the recovery half: a
/// reinstall that replaced the harness tree lost the projection, and the next
/// compile restores it from the record.
///
/// It runs before the compile, because the fold-back only carries a scope
/// whose identity file exists. An identity file that is present is never
/// overwritten, so a hand edit to it survives; the grid column always comes
/// from the record regardless.
///
/// # Errors
///
/// A record does not parse, or a file cannot be written.
pub fn materialize_identities(
    project: &Path,
    records_dir: &Path,
    scopes_dir: &Path,
) -> Result<Vec<PathBuf>> {
    let mut records = load_records(records_dir)?;
    records.sort_by(|a, b| cmp_utf16(&a.name, &b.name));
    let mut written = Vec::new();
    for record in records {
        if identity_file_for(scopes_dir, &record.name).is_some() {
            continue;
        }
        let restored =
            file_inside(scopes_dir, &format!("focus-{}.md", record.name)).and_then(|target| {
                refuse_link_on_the_way(project, &target)?;
                make_dir(scopes_dir)?;
                observer::refuse_write(observer::WRITE_FILE_ATOMIC)?;
                write_atomic(&target, record.identity.as_bytes())
                    .map_err(|err| EngineError::new(format!("{}: {err}", target.display())))?;
                Ok(target)
            });
        match restored {
            Ok(target) => written.push(target),
            Err(err) => {
                // All or nothing: a caller that is told this failed is not
                // left with the files restored before the failure.
                for path in &written {
                    let _ = std::fs::remove_file(path);
                }
                return Err(err);
            }
        }
    }
    Ok(written)
}

/// Give a record to each composed scope that exists only in the harness tree
/// (identity file plus grid column). One-way and one-time: once the record
/// exists it is the source and this does nothing.
///
/// It runs after the compile, because the emitted grid is what names those
/// scopes and carries their cells. An existing record is never overwritten.
///
/// # Errors
///
/// An identity file that already contains a sentinel, or a failed write.
pub fn backfill_records(
    project: &Path,
    records_dir: &Path,
    scopes_dir: &Path,
    grid_only_names: &[String],
    grid_json: &str,
) -> Result<Vec<String>> {
    if grid_only_names.is_empty() {
        return Ok(Vec::new());
    }
    let Ok(Value::Object(grid)) = json::parse(grid_json) else {
        return Ok(Vec::new());
    };
    let mut written = Vec::new();
    for name in grid_only_names {
        if !is_scope_name(name) {
            continue;
        }
        let Some(Value::Object(stages)) = grid.get(name).and_then(|entry| entry.get("stages"))
        else {
            continue;
        };
        let Some(identity_path) = identity_file_for(scopes_dir, name) else {
            continue;
        };
        let target = file_inside(records_dir, &format!("{name}.md"))?;
        if target.exists() {
            continue;
        }
        refuse_link_on_the_way(project, &target)?;
        make_dir(records_dir)?;
        let rendered = render_record(
            &read_text(&identity_path)?,
            stages,
            Some(&identity_path.display().to_string()),
        )?;
        observer::refuse_write(observer::WRITE_FILE_ATOMIC)?;
        write_atomic(&target, rendered.as_bytes())
            .map_err(|err| EngineError::new(format!("{}: {err}", target.display())))?;
        written.push(name.clone());
    }
    Ok(written)
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    const IDENTITY: &str = "---\nname: spike\ndepth: minimal\n---\n\n# Spike\n\nA ```json fence of my own:\n\n```json\n{\"stages\": {\"not\": \"the grid\"}}\n```\n";

    fn stages() -> Map<String, Value> {
        json!({"workspace-detection": "EXECUTE", "code-generation": "EXECUTE", "build-and-test": "SKIP"})
            .as_object()
            .unwrap()
            .clone()
    }

    #[test]
    fn a_record_round_trips_through_render_and_parse() {
        let rendered = render_record(IDENTITY, &stages(), None).unwrap();
        let record = parse_record(&rendered, "spike.md").unwrap();
        assert_eq!(record.name, "spike");
        // The fence in the authored prose is not mistaken for the grid.
        assert_eq!(record.stages, stages());
        assert_eq!(record.identity, IDENTITY);
        assert_eq!(
            render_record(&record.identity, &record.stages, None).unwrap(),
            rendered
        );
    }

    #[test]
    fn malformed_records_are_refused_by_name() {
        let good = render_record(IDENTITY, &stages(), None).unwrap();
        let message = |body: &str| parse_record(body, "r.md").unwrap_err().message().to_owned();

        assert_eq!(
            message("no frontmatter"),
            "Composed scope record missing frontmatter: r.md"
        );
        assert!(
            message(IDENTITY)
                .starts_with("Composed scope record r.md has no generated grid region.")
        );
        assert_eq!(
            message(&format!("{good}{GRID_END}\n")),
            "Composed scope record r.md has 1 BEGIN and 2 END grid sentinels; exactly one of each is required. Remove the duplicates so the generated region is unambiguous."
        );
        assert_eq!(
            message(&good.replace("\"SKIP\"", "\"MAYBE\"")),
            "Composed scope record r.md: stage \"build-and-test\" has invalid action \"MAYBE\" (expected EXECUTE or SKIP)."
        );
        assert_eq!(
            message(&format!("{IDENTITY}\n{GRID_END}\n{GRID_BEGIN}\n")),
            "Composed scope record r.md has its END grid sentinel before its BEGIN sentinel."
        );
        assert_eq!(
            render_record(&good, &stages(), Some("x.md"))
                .unwrap_err()
                .message(),
            "Composed scope identity x.md already contains an focus composed-scope-grid sentinel; it must hold only the authored scope file, not a generated grid region."
        );
    }

    #[test]
    fn records_win_over_grid_columns_and_orphans_are_left_out() {
        let record = Record {
            name: "spike".to_owned(),
            identity: IDENTITY.to_owned(),
            stages: stages(),
        };
        let on_disk = json!({
            "feature": {"stages": {"a": "EXECUTE"}},
            "spike": {"stages": {"stale": "EXECUTE"}},
            "legacy": {"stages": {"a": "SKIP"}},
            "orphan": {"stages": {"a": "SKIP"}},
            "not a name": {"stages": {}},
        })
        .to_string();
        let folded = fold_back(
            &[record],
            Some(&on_disk),
            &["feature"],
            &["feature", "spike", "legacy"],
        );
        assert_eq!(folded.names, ["legacy", "spike"]);
        assert_eq!(folded.record_names, ["spike"]);
        assert_eq!(folded.grid_only_names, ["legacy"]);
        assert_eq!(folded.grid["spike"]["stages"], Value::Object(stages()));
        assert!(!folded.grid.contains_key("orphan"));

        let fresh = json!({"feature": {"stages": {"a": "EXECUTE"}}})
            .as_object()
            .unwrap()
            .clone();
        let merged: Vec<String> = merge(fresh, &folded).keys().cloned().collect();
        assert_eq!(merged, ["feature", "legacy", "spike"]);
    }

    /// Deliberate deviation. Upstream keeps records in a plain JS object and
    /// tests membership with `in` and truthiness, so a scope named after an
    /// `Object.prototype` member is reported as a duplicate (`constructor`,
    /// `toString`, `valueOf`, ...) or silently dropped from the merged grid.
    /// Focus treats such a name like any other.
    #[test]
    fn a_scope_named_like_an_object_prototype_member_is_an_ordinary_scope() {
        let dir = std::env::temp_dir().join(format!("focus-composed-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let identity = IDENTITY.replace("name: spike", "name: constructor");
        std::fs::write(
            dir.join("constructor.md"),
            render_record(&identity, &stages(), None).unwrap(),
        )
        .unwrap();
        let records = load_records(&dir).unwrap();
        assert_eq!(records[0].name, "constructor");

        let folded = fold_back(&records, None, &[], &["constructor"]);
        let merged = merge(Map::new(), &folded);
        assert!(merged.contains_key("constructor"));
        std::fs::remove_dir_all(&dir).unwrap();
    }

    /// The write creates no directory, so restoring a scope makes the one it
    /// goes into, as upstream does before its own write.
    #[test]
    fn a_scope_is_restored_into_a_directory_that_was_not_there() {
        let project = std::env::temp_dir().join(format!("focus-restore-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&project);
        let (records, scopes) = (project.join("records"), project.join("harness/scopes"));
        std::fs::create_dir_all(&records).unwrap();
        std::fs::write(
            records.join("spike.md"),
            render_record(IDENTITY, &stages(), None).unwrap(),
        )
        .unwrap();
        let written = materialize_identities(&project, &records, &scopes).unwrap();
        assert_eq!(written, [scopes.join("focus-spike.md")]);
        assert_eq!(std::fs::read_to_string(&written[0]).unwrap(), IDENTITY);
        std::fs::remove_dir_all(&project).unwrap();
    }
}
